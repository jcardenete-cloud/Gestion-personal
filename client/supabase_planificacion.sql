create table if not exists jcf.planificacion (
  id bigint generated by default as identity primary key,
  codigopr text not null,
  anio smallint not null check (anio between 1900 and 9999),
  mes smallint not null check (mes between 1 and 12),
  perfil text not null,
  horas numeric(12, 2) not null check (horas >= 0),
  created_at timestamptz not null default now(),
  unique (codigopr, anio, mes, perfil)
);

alter table jcf.planificacion enable row level security;

drop policy if exists "Authenticated users can manage planificacion" on jcf.planificacion;
create policy "Authenticated users can manage planificacion"
  on jcf.planificacion
  for all
  to authenticated
  using (true)
  with check (true);

grant usage on schema jcf to authenticated;
grant select, insert, update on jcf.planificacion to authenticated;
grant usage, select on sequence jcf.planificacion_id_seq to authenticated;
