create table if not exists jcf.mediciones (
  id bigint generated by default as identity primary key,
  codigopr text not null,
  anio smallint not null check (anio between 1900 and 9999),
  mes smallint not null check (mes between 1 and 12),
  perfil text not null,
  horas numeric(12, 2) not null check (horas >= 0),
  created_at timestamptz not null default now(),
  unique (codigopr, anio, mes, perfil)
);

alter table jcf.mediciones enable row level security;

drop policy if exists "Authenticated users can manage mediciones" on jcf.mediciones;
create policy "Authenticated users can manage mediciones"
  on jcf.mediciones
  for all
  to authenticated
  using (true)
  with check (true);

grant usage on schema jcf to authenticated;
grant select, insert, update on jcf.mediciones to authenticated;
grant usage, select on sequence jcf.mediciones_id_seq to authenticated;
